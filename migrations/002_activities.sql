
-- GOFOLKS: activities and participants

CREATE TABLE IF NOT EXISTS activities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    creator_id BIGINT NOT NULL
        REFERENCES users(id) ON DELETE CASCADE,
    title VARCHAR(150) NOT NULL,
    description TEXT NOT NULL DEFAULT '',
    location VARCHAR(255) NOT NULL DEFAULT '',
    activity_date TIMESTAMPTZ,
    max_participants INTEGER NOT NULL DEFAULT 2
        CHECK (max_participants >= 2),
    status VARCHAR(20) NOT NULL DEFAULT 'open'
        CHECK (status IN ('open', 'full', 'cancelled', 'completed')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_activities_created_at
    ON activities(created_at DESC);

CREATE INDEX IF NOT EXISTS idx_activities_creator_id
    ON activities(creator_id);

CREATE TABLE IF NOT EXISTS activity_participants (
    activity_id BIGINT NOT NULL
        REFERENCES activities(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL
        REFERENCES users(id) ON DELETE CASCADE,
    joined_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (activity_id, user_id)
);

CREATE INDEX IF NOT EXISTS idx_activity_participants_user_id
    ON activity_participants(user_id);

ALTER TABLE chats
    ADD COLUMN IF NOT EXISTS activity_id BIGINT
    REFERENCES activities(id) ON DELETE CASCADE;

CREATE UNIQUE INDEX IF NOT EXISTS idx_chats_activity_id
    ON chats(activity_id)
    WHERE activity_id IS NOT NULL;
